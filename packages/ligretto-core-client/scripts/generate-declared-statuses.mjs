/**
 * Writes `src/generated/declared-statuses.ts` from `apps/ligretto-core-backend/openapi.json` and `openapi.internal.json`: the
 * statuses every operation declares, keyed `'<METHOD> <path template>'`, which is exactly the `method` and `url` a
 * generated operation passes to the transport. The transport looks an answer's status up here to tell an answer
 * inside the contract from one outside it, so the result types never claim a status the document does not declare.
 *
 * Both documents are merged into one map: `GET /health` is in both and declares the same statuses in each, and every
 * other path belongs to one of them. A path in both with different statuses is refused rather than merged.
 *
 * The output is a pure function of the documents: keys and statuses are sorted with a plain comparison (no locale),
 * and the template is fixed with nothing stamped into it, so regenerating unchanged documents writes the same bytes.
 * The file sits beside the two directories kubb cleans, so `kubb generate` leaves it alone.
 *
 * Dev-time only. It runs under Node, after `kubb generate`; nothing in `src/` imports it.
 */

import { readFileSync, writeFileSync } from 'node:fs'

const documents = ['openapi.json', 'openapi.internal.json']
const outputUrl = new URL('../src/generated/declared-statuses.ts', import.meta.url)

const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']

const ascending = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/** `'<METHOD> <path>'` → its statuses, sorted. */
const declared = new Map()

for (const name of documents) {
  const document = JSON.parse(readFileSync(new URL(`../../../apps/ligretto-core-backend/${name}`, import.meta.url), 'utf8'))
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    for (const method of METHODS) {
      const operation = item[method]
      if (operation === undefined) {
        continue
      }
      const key = `${method.toUpperCase()} ${path}`
      const statuses = Object.keys(operation.responses ?? {})
        .map(Number)
        .sort((a, b) => a - b)
      const known = declared.get(key)
      if (known !== undefined && known.join() !== statuses.join()) {
        throw new Error(`${key} declares ${known.join(', ')} in one document and ${statuses.join(', ')} in ${name}.`)
      }
      declared.set(key, statuses)
    }
  }
}

const entries = [...declared.entries()].sort(([a], [b]) => ascending(a, b))

const file = `/**
* Generated by scripts/generate-declared-statuses.mjs from apps/ligretto-core-backend/openapi.json and openapi.internal.json.
* Do not edit manually.
*/

/**
 * The statuses each operation of both documents declares, keyed \`'<METHOD> <path template>'\` as a generated operation
 * passes them to the transport. An answer with a status missing here is outside the contract.
 */
export const declaredStatuses: Readonly<Record<string, readonly number[] | undefined>> = {
${entries.map(([key, statuses]) => `  '${key}': [${statuses.join(', ')}],`).join('\n')}
}
`

writeFileSync(outputUrl, file)
