/**
 * Writes `src/generated/error-codes.ts` from the `x-error-codes` extension of `apps/cas/openapi.json`, for the same
 * paths kubb mirrors (`/oidc/*` and `/.well-known/*`).
 *
 * The extension is the one place the codes live, whatever the response body (ADR 0016 (i)): the `302` of
 * `/oidc/authorize` carries its ten codes in the redirect's `error` query parameter and has no body at all, and the
 * `400`/`503` of the navigation endpoints are HTML pages. A generator that read response schemas would drop them.
 *
 * The output is a pure function of the description: keys, statuses and codes are sorted with a plain comparison (no
 * locale), and the template is fixed with nothing stamped into it. Regenerating an unchanged description rewrites
 * the same bytes, which is what the pull request job diffs.
 *
 * Dev-time only. It runs under Node, after `kubb generate` has emptied `src/generated`; nothing in `src/` imports it.
 */

import { readFileSync, writeFileSync } from 'node:fs'

const specUrl = new URL('../../../apps/cas/openapi.json', import.meta.url)
const outputUrl = new URL('../src/generated/error-codes.ts', import.meta.url)

/** The same selection as `kubb.config.ts`. */
const isMirrored = path => path.startsWith('/oidc/') || path.startsWith('/.well-known/')

const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']

const ascending = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

const spec = JSON.parse(readFileSync(specUrl, 'utf8'))

const operations = []
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  if (!isMirrored(path)) {
    continue
  }
  for (const method of METHODS) {
    const operation = item[method]
    if (operation === undefined) {
      continue
    }
    const statuses = Object.entries(operation.responses ?? {})
      .filter(([, response]) => Array.isArray(response['x-error-codes']))
      .map(([status, response]) => [status, [...response['x-error-codes']].sort(ascending)])
      .sort(([a], [b]) => ascending(a, b))
    if (statuses.length > 0) {
      operations.push([`${method.toUpperCase()} ${path}`, statuses])
    }
  }
}
operations.sort(([a], [b]) => ascending(a, b))

const codes = [...new Set(operations.flatMap(([, statuses]) => statuses.flatMap(([, forStatus]) => forStatus)))].sort(ascending)

const quoted = value => `'${value}'`

const map = operations
  .map(([operation, statuses]) => {
    const body = statuses.map(([status, forStatus]) => `    '${status}': [${forStatus.map(quoted).join(', ')}],`).join('\n')
    return `  '${operation}': {\n${body}\n  },`
  })
  .join('\n')

const file = `/**
* Generated by scripts/generate-error-codes.mjs from apps/cas/openapi.json.
* Do not edit manually.
*/

/**
 * The error codes each mirrored operation answers with, per status, as \`x-error-codes\` lists them (ADR 0016 (i)).
 * Keyed \`'<METHOD> <path>'\`. A status with no entry here has no error code: it either cannot fail that way or
 * answers a success.
 */
export const errorCodes = {
${map}
} as const

/** Every error code the mirrored operations can answer with. */
export type OidcErrorCode =
${codes.map(code => `  | ${quoted(code)}`).join('\n')}
`

writeFileSync(outputUrl, file)
